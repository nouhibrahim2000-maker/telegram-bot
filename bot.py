def load_media():
    with open(MEDIA_DB, "r") as f:
        return json.load(f)

def save_media(media_list):
    with open(MEDIA_DB, "w") as f:
        json.dump(media_list, f)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text("البوت شغال. ابعت صور أو فيديو أو GIF وأنا هخزنهم. استخدم /mom أو /sister عشان أذلك.")

async def send_random(update: Update, context: ContextTypes.DEFAULT_TYPE):
    msg = random.choice(messages)
    await update.message.reply_text(msg)
    
    media_list = load_media()
    if media_list:
        item = random.choice(media_list)
        file_path = item["path"]
        media_type = item["type"]
        
        with open(file_path, "rb") as f:
            if media_type == "photo":
                await update.message.reply_photo(f)
            elif media_type == "video":
                await update.message.reply_video(f)
            elif media_type == "animation":
                await update.message.reply_animation(f)

async def handle_media(update: Update, context: ContextTypes.DEFAULT_TYPE):
    message = update.message
    file_id = None
    media_type = None
    ext = ".jpg"
    
    if message.photo:
        file_id = message.photo[-1].file_id
        media_type = "photo"
        ext = ".jpg"
    elif message.video:
        file_id = message.video.file_id
        media_type = "video"
        ext = ".mp4"
    elif message.animation:
        file_id = message.animation.file_id
        media_type = "animation"
        ext = ".mp4"
    elif message.document and message.document.mime_type and "gif" in message.document.mime_type:
        file_id = message.document.file_id
        media_type = "animation"
        ext = ".gif"
    
    if file_id:
        file = await context.bot.get_file(file_id)
        filename = f"{MEDIA_FOLDER}/{file_id}{ext}"
        await file.download_to_drive(filename)
        
        media_list = load_media()
        media_list.append({"path": filename, "type": media_type})
        save_media(media_list)
        
        await update.message.reply_text("اتحفظ. هبعتلك منه عشوائي لما تطلب /mom أو /sister.")

def main():
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("mom", send_random))
    app.add_handler(CommandHandler("sister", send_random))
    app.add_handler(MessageHandler(filters.PHOTO | filters.VIDEO | filters.ANIMATION | filters.Document.GIF, handle_media))
    app.run_polling()

if __name__ == "__main__":
    main()
